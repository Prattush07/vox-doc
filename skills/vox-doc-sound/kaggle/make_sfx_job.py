"""Free AI sound effects: a list of prompts -> a ready-to-push Kaggle job (Stable Audio Open 1.0)

    python kaggle/make_sfx_job.py my_sounds.tsv --user <kaggle-username>
    python -m kaggle.cli kernels push -p sfx_job
    python -m kaggle.cli kernels status <kaggle-username>/free-sfx
    python -m kaggle.cli kernels output <kaggle-username>/free-sfx -p sfx_out --file-pattern "\\.wav$|\\.log$"
    then move sfx_out/sfx/* into sfx/StableAudio/ and run: python scripts/index_sfx.py

my_sounds.tsv columns: category, name, seconds, prompt   (seconds up to 47)

Why this one: it is free (Kaggle's T4 GPU, about 30 h/week), and under the
Stability AI Community License "You own any outputs generated from the Models".
You may use them commercially while your yearly revenue is under $1M. You may
not use them to train other AI models. Good for whooshes, risers, ambience,
foley. Weak at exact UI clicks: use the Kenney CC0 sounds in sfx/Kenney_CC0/
for those.

No Hugging Face token or Kaggle secret is needed: the weights come from the
ungated ModelsLab/stable-audio-open-1.0 mirror, pinned to a revision that is
byte-identical to the official gated repo. The Stability AI Community License
still applies to the outputs (https://huggingface.co/stabilityai/stable-audio-open-1.0).
Fallback: if the log says "mirror failed", accept the terms on that page, create a
Read token at https://huggingface.co/settings/tokens, and add it on the notebook page:
Add-ons -> Secrets -> HF_TOKEN -> attach -> Save Version. Then push again.
Prompt tips: describe the sound and say "clean high quality sound effect,
isolated"; ambience: add "steady, no music". About 20-60 s per sound on a T4.
"""
import argparse, csv, json, os

RUN = r'''# generated by make_sfx_job.py -- edit the TSV and regenerate, not this file
import json, os, subprocess, sys
os.environ.update(USE_TF="0", USE_TORCH="1", USE_JAX="0", USE_FLAX="0")
# new diffusers trips on Kaggle's torchao (FqnToConfig); nothing here needs torchao
subprocess.run([sys.executable, "-m", "pip", "uninstall", "-y", "-q", "torchao"], check=False)
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-U", "diffusers", "torchsde"], check=True)
import soundfile as sf, torch
from diffusers import StableAudioPipeline

ROWS = json.loads(%(rows)r)
NEG = "low quality, distorted, music, melody, speech, voice, singing, noise, clipping"
try:      # ungated mirror, byte-identical to the official repo: no token needed
    pipe = StableAudioPipeline.from_pretrained("ModelsLab/stable-audio-open-1.0",
                                               revision="836348c7020297467318078dd37a04ecd709fe75",
                                               torch_dtype=torch.float16).to("cuda")
except Exception as e:   # mirror gone: official gated repo, needs the HF_TOKEN Kaggle secret
    print("mirror failed (" + str(e)[:200] + "); using stabilityai/stable-audio-open-1.0 with HF_TOKEN", flush=True)
    from kaggle_secrets import UserSecretsClient
    os.environ["HF_TOKEN"] = UserSecretsClient().get_secret("HF_TOKEN")
    pipe = StableAudioPipeline.from_pretrained("stabilityai/stable-audio-open-1.0",
                                               torch_dtype=torch.float16).to("cuda")
for cat, name, secs, prompt in ROWS:
    os.makedirs(f"/kaggle/working/sfx/{cat}", exist_ok=True)
    g = torch.Generator("cuda").manual_seed(0)
    audio = pipe(prompt, negative_prompt=NEG, num_inference_steps=150, audio_end_in_s=float(secs),
                 num_waveforms_per_prompt=1, generator=g).audios[0]
    a = audio.T.float().cpu().numpy()
    a = a / max(float(abs(a).max()), 1e-9) * 0.89     # 16-bit WAV clips anything above 1.0
    sf.write(f"/kaggle/working/sfx/{cat}/{name}.wav", a, pipe.vae.sampling_rate)
    print(f"{cat}/{name} {secs}s ok", flush=True)
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("tsv", help="category, name, seconds, prompt")
    ap.add_argument("--user", required=True, help="your Kaggle username")
    ap.add_argument("--slug", default="free-sfx")
    ap.add_argument("--out", default="sfx_job")
    a = ap.parse_args()
    with open(a.tsv, encoding="utf-8") as f:
        rows = [(r["category"], r["name"], float(r["seconds"]), r["prompt"])
                for r in csv.DictReader(f, delimiter="\t")]
    assert all(0 < r[2] <= 47 for r in rows), "seconds must be 1-47"
    os.makedirs(a.out, exist_ok=True)
    with open(f"{a.out}/run.py", "w", encoding="utf-8") as f:
        f.write(RUN % {"rows": json.dumps(rows, ensure_ascii=False)})
    meta = {"id": f"{a.user}/{a.slug}", "title": a.slug.replace("-", " "), "code_file": "run.py",
            "language": "python", "kernel_type": "script", "is_private": True,
            "enable_gpu": True, "enable_internet": True, "machine_shape": "NvidiaTeslaT4",
            "dataset_sources": [], "competition_sources": [], "kernel_sources": [], "model_sources": []}
    with open(f"{a.out}/kernel-metadata.json", "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=1)
    print(f"{a.out}/ ready: {len(rows)} sounds. Push: python -m kaggle.cli kernels push -p {a.out}")


if __name__ == "__main__":
    main()
