"""LINES.tsv -> a ready-to-push Kaggle job that voices every line with Indic Parler-TTS

    python kaggle/make_parler_job.py LINES.tsv --user <kaggle-username> --speaker Aman
    python -m kaggle.cli kernels push -p parler_job
    python -m kaggle.cli kernels status <kaggle-username>/parler-vo
    python -m kaggle.cli kernels output <kaggle-username>/parler-vo -p parler_out --file-pattern "\\.wav$|\\.log$"
    python scripts/vo_join.py parler_out/takes LINES.tsv --out VO

Indic Parler-TTS (AI4Bharat, Apache 2.0, commercial OK) speaks Hindi and 20
other Indian languages plus English. It needs a GPU, so it runs on Kaggle's free
T4 when this machine is too small.

No Hugging Face token or Kaggle secret is needed. The model comes from the
ungated RXD03/indic-parler-tts mirror, pinned to a revision whose
model.safetensors and tokenizer.model are byte-identical to the official
ai4bharat repo, and whose config and tokenizer files have the same content
(only the JSON formatting differs). Licence: Apache 2.0.
Only a Kaggle account (phone-verified, for the GPU) and its API token are needed.
Fallback: if the log says "mirror failed", accept the terms at
https://huggingface.co/ai4bharat/indic-parler-tts, create a Read token at
https://huggingface.co/settings/tokens, and add it on the notebook page:
Add-ons -> Secrets -> HF_TOKEN -> attach -> Save Version. Then push again.

Speakers worth trying for documentary narration: Aman, Kabir, Bhanu, Dinesh,
Aakash (male); Divya, Nisha (female). Rohit sounds robotic.
"""
import argparse, csv, json, os

STYLES = {
    "doc": "{} speaks with a clear, confident and engaging voice at a moderate pace, with "
           "expressive intonation, like a documentary narrator telling a fascinating story. "
           "The recording is very close to the microphone, very clear audio with no background noise.",
    "calm": "{} speaks slowly and calmly with a warm, deep voice and gentle pauses, like a thoughtful "
            "documentary narrator. The recording is very close to the microphone, very clear audio "
            "with no background noise.",
}

RUN = r'''# generated by make_parler_job.py -- edit LINES / DESC there, not here
import json, os, subprocess, sys
# parler pins an old transformers that imports Kaggle's TensorFlow and dies on protobuf
os.environ.update(USE_TF="0", USE_TORCH="1", USE_JAX="0", USE_FLAX="0")
subprocess.run([sys.executable, "-m", "pip", "install", "-q",
                "git+https://github.com/huggingface/parler-tts.git"], check=True)
import soundfile as sf, torch
from parler_tts import ParlerTTSForConditionalGeneration
from transformers import AutoTokenizer

LINES = json.loads(%(lines)r)
DESC = %(desc)r
try:      # ungated mirror, same files as the official repo: no token needed
    M, REV = "RXD03/indic-parler-tts", "6ffcecc3b3d72a6256019897be0610fa3317bec2"
    model = ParlerTTSForConditionalGeneration.from_pretrained(M, revision=REV).to("cuda")
except Exception as e:   # mirror gone: official gated repo, needs the HF_TOKEN Kaggle secret
    print("mirror failed (" + str(e)[:200] + "); using ai4bharat/indic-parler-tts with HF_TOKEN", flush=True)
    from kaggle_secrets import UserSecretsClient
    os.environ["HF_TOKEN"] = UserSecretsClient().get_secret("HF_TOKEN")
    M, REV = "ai4bharat/indic-parler-tts", None
    model = ParlerTTSForConditionalGeneration.from_pretrained(M).to("cuda")
tok = AutoTokenizer.from_pretrained(M, revision=REV)
dtok = AutoTokenizer.from_pretrained(model.config.text_encoder._name_or_path)
sr = model.config.sampling_rate
d = dtok(DESC, return_tensors="pt").to("cuda")
os.makedirs("/kaggle/working/takes", exist_ok=True)
for i, text in LINES:
    torch.manual_seed(0)
    p = tok(text, return_tensors="pt").to("cuda")
    with torch.no_grad():
        g = model.generate(input_ids=d.input_ids, attention_mask=d.attention_mask,
                           prompt_input_ids=p.input_ids, prompt_attention_mask=p.attention_mask)
    a = g.cpu().float().numpy().squeeze()
    sf.write(f"/kaggle/working/takes/{i}.wav", a, sr)
    print(f"[{i}] {len(a)/sr:5.2f}s", flush=True)
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("lines", help="LINES.tsv: id, text, gap")
    ap.add_argument("--user", required=True, help="your Kaggle username")
    ap.add_argument("--speaker", default="Aman")
    ap.add_argument("--style", default="doc", choices=sorted(STYLES))
    ap.add_argument("--slug", default="parler-vo")
    ap.add_argument("--out", default="parler_job")
    a = ap.parse_args()
    with open(a.lines, encoding="utf-8") as f:
        rows = [(r["id"], r["text"]) for r in csv.DictReader(f, delimiter="\t")]
    os.makedirs(a.out, exist_ok=True)
    with open(f"{a.out}/run.py", "w", encoding="utf-8") as f:
        f.write(RUN % {"lines": json.dumps(rows, ensure_ascii=False),
                       "desc": STYLES[a.style].format(a.speaker)})
    meta = {"id": f"{a.user}/{a.slug}", "title": a.slug.replace("-", " "), "code_file": "run.py",
            "language": "python", "kernel_type": "script", "is_private": True,
            "enable_gpu": True, "enable_internet": True, "machine_shape": "NvidiaTeslaT4",
            "dataset_sources": [], "competition_sources": [], "kernel_sources": [], "model_sources": []}
    with open(f"{a.out}/kernel-metadata.json", "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=1)
    print(f"{a.out}/ ready: {len(rows)} lines, speaker {a.speaker}, style {a.style}")
    print(f"push: python -m kaggle.cli kernels push -p {a.out}")


if __name__ == "__main__":
    main()
